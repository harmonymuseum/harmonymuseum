"""GitHub Pages has no server-side redirects, so the old WordPress URLs in _redirects
become tiny pages that forward to their new home (meta refresh + canonical, which
search engines treat as a permanent move). Wildcard rules (/events/*) and anything
that can't be a page (the old PDF) go into a map inside 404.html instead.

_redirects stays the one list to edit. After changing it:  python3 tools/make_redirect_stubs.py
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
os.chdir(ROOT)
SITE = "https://harmonymuseum.org"
MARK = re.compile(r"(/\* redirects:start \*/).*?(/\* redirects:end \*/)", re.S)

STUB = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<!-- Generated by tools/make_redirect_stubs.py from _redirects. Do not edit. -->
<meta http-equiv="refresh" content="0; url={to}"><link rel="canonical" href="{site}{to}">
<title>Moved — Harmony Museum</title><script>location.replace("{to}")</script></head>
<body><p>This page has moved: <a href="{to}">{site}{to}</a></p></body></html>
"""

rules = []
for line in open("_redirects", encoding="utf-8"):
    parts = line.split()
    if len(parts) >= 2 and parts[0].startswith("/"):
        rules.append((parts[0], parts[1]))

stubs, mapped = [], {}
for src, to in rules:
    if src.endswith("*") or src.endswith(".pdf"):
        mapped[src] = to
        continue
    path = src.lstrip("/")
    out = path if path.endswith(".html") else os.path.join(path, "index.html")
    if os.path.exists(out) and "<!-- Generated by tools/make_redirect_stubs.py" not in open(out, encoding="utf-8").read():
        print(f"skip {out}: a real file is already there")
        continue
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(STUB.format(to=to, site=SITE))
    stubs.append(out)

page = open("404.html", encoding="utf-8").read()
if not MARK.search(page):
    sys.exit("404.html is missing the /* redirects:start */ … /* redirects:end */ markers")
js = "var R = " + json.dumps(mapped, indent=1) + ";"
page = MARK.sub(lambda m: m.group(1) + "\n" + js + "\n" + m.group(2), page)
with open("404.html", "w", encoding="utf-8", newline="\n") as f:
    f.write(page)
print(f"{len(stubs)} stub pages, {len(mapped)} rules in 404.html")
